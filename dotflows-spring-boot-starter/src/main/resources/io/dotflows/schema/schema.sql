-- dot-flows schema. Works on PostgreSQL and H2. Safe to run repeatedly.
-- Applied automatically at startup unless dotflows.initialize-schema=false, in which case run it
-- through your own migration tool.

CREATE TABLE IF NOT EXISTS dflow_definition (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind       VARCHAR(16)  NOT NULL,
    def_key    VARCHAR(100) NOT NULL,
    version    INT          NOT NULL,
    status     VARCHAR(16)  NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT FALSE,
    name       VARCHAR(255),
    body       TEXT         NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT dflow_definition_uq UNIQUE (kind, def_key, version)
);

CREATE TABLE IF NOT EXISTS dflow_instance (
    id              VARCHAR(36)  PRIMARY KEY,
    definition_id   BIGINT       NOT NULL REFERENCES dflow_definition (id),
    process_key     VARCHAR(100) NOT NULL,
    version         INT          NOT NULL,
    business_key    VARCHAR(255),
    status          VARCHAR(16)  NOT NULL,
    variables       TEXT         NOT NULL,
    current_node_id VARCHAR(255),
    error           TEXT,
    started_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at        TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS dflow_instance_started_idx ON dflow_instance (started_at);
CREATE INDEX IF NOT EXISTS dflow_instance_key_idx ON dflow_instance (process_key, started_at);
CREATE INDEX IF NOT EXISTS dflow_instance_status_idx ON dflow_instance (status, started_at);
CREATE INDEX IF NOT EXISTS dflow_instance_business_key_idx ON dflow_instance (business_key);

CREATE TABLE IF NOT EXISTS dflow_step (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance_id VARCHAR(36)  NOT NULL REFERENCES dflow_instance (id) ON DELETE CASCADE,
    node_id     VARCHAR(255) NOT NULL,
    node_type   VARCHAR(32)  NOT NULL,
    status      VARCHAR(16)  NOT NULL,
    attempt     INT          NOT NULL,
    started_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    error       TEXT,
    output      TEXT
);

CREATE INDEX IF NOT EXISTS dflow_step_instance_idx ON dflow_step (instance_id, id);

CREATE TABLE IF NOT EXISTS dflow_job (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance_id  VARCHAR(36)  NOT NULL REFERENCES dflow_instance (id) ON DELETE CASCADE,
    node_id      VARCHAR(255) NOT NULL,
    due_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    attempt      INT          NOT NULL,
    lock_token   VARCHAR(36),
    locked_until TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS dflow_job_due_idx ON dflow_job (due_at);
CREATE INDEX IF NOT EXISTS dflow_job_instance_idx ON dflow_job (instance_id);
